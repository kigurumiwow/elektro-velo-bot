def generate_contract_pdf(data: dict) -> io.BytesIO:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        leftMargin=16 * mm, rightMargin=16 * mm, topMargin=13 * mm, bottomMargin=13 * mm
    )
    flow = build_contract_flowables(data)
    doc.build(flow)
    buf.seek(0)
    return buf
